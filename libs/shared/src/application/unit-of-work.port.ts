/**
 * Одна транзакция на одно решение.
 *
 * В сигнатуре нет дескриптора транзакции: иначе его пришлось бы протаскивать
 * через каждый метод репозитория, и любой забытый аргумент молча писал бы вне
 * транзакции. Адаптер передаёт его репозиториям сам, через асинхронный контекст.
 */
export abstract class UnitOfWork {
  abstract run<T>(work: () => Promise<T>): Promise<T>;
}
